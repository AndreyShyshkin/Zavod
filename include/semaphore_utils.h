/**
 * @file semaphore_utils.h
 * @brief Модуль керування іменованим семафором для регулювання перерв робітників (Issue #4).
 * @details Забезпечує взаємне виключення (не більше одного робітника на перерві одночасно)
 *          та атомарний запис подій у файл журналу break_log.txt.
 * 
 * ============================================================================
 * ОБҐРУНТУВАННЯ ВИБОРУ POSIX СЕМАФОРІВ НАД SYSTEM V:
 * 1. Сучасний стандарт: POSIX.1b є стандартом реального часу для Linux,
 *    на відміну від застарілих та складних у супроводі засобів System V IPC.
 * 2. Простір імен: Іменування семафора через зрозумілий рядок ("/zavod_break_sem")
 *    відображається у віртуальній пам'яті ядра /dev/shm, що гарантує відсутність
 *    конфліктів та колізій ключів ftok.
 * 3. Надійність та простота API: Лаконічні функції sem_wait() та sem_post()
 *    не вимагають ініціалізації складних структур struct sembuf та об'єднань union semun.
 * 4. Контроль життєвого циклу: Механізм sem_unlink() забезпечує коректне
 *    видалення семафора з системи, а sem_close() — звільнення дескриптора процесом.
 * ============================================================================
 */

#ifndef SEMAPHORE_UTILS_H
#define SEMAPHORE_UTILS_H

#include <stdbool.h>
#include <semaphore.h>
#include "common.h"

/**
 * @brief Ініціалізує іменований POSIX-семафор для контролю кімнати відпочинку.
 * @details Якщо семафор ще не створено в системі, створює його з початковим значенням 1
 *          та правами доступу SEM_PERMS (0644). Якщо вже створено іншим процесом,
 *          підключається до існуючого дескриптора.
 * 
 * @return ZAVOD_SUCCESS (0) у разі успішного відкриття або підключення.
 * @return ZAVOD_ERR_SEM (-2) у разі помилки системного виклику sem_open().
 * 
 * @note Батьківський процес викликає цю функцію першим для реєстрації себе як творця.
 * @see cleanup_break_semaphore()
 */
int init_break_semaphore(void);

/**
 * @brief Блокуючий вхід робітника до кімнати відпочинку (захоплення семафора).
 * @details Виконує перевірку валідності ідентифікатора worker_id, після чого викликає
 *          sem_wait(). У разі успіху фіксує поточний системний час початку відпочинку.
 * 
 * @param[in] worker_id Числовий ідентифікатор робітника (має бути > 0 та < MAX_TRACKED_WORKERS).
 * 
 * @return ZAVOD_SUCCESS (0) при успішному отриманні доступу до кімнати відпочинку.
 * @return ZAVOD_ERR_INVALID_ARG (-6) якщо worker_id виходить за межі допустимих значень.
 * @return ZAVOD_ERR_SEM (-2) у разі фатальної помилки sem_wait().
 * 
 * @warning Якщо семафор зайнятий іншим робітником, поточний процес блокується до sem_post().
 */
int leave_for_break(int worker_id);

/**
 * @brief Вихід робітника з кімнати відпочинку (звільнення семафора та логування).
 * @details Фіксує поточний час завершення перерви, формує запис у форматі:
 *          "[Робітник %d] Вихід: %s — Повернення: %s\n" та атомарно записує його
 *          у break_log.txt через прапорець O_APPEND. Після цього викликає sem_post().
 * 
 * @param[in] worker_id Числовий ідентифікатор робітника.
 * 
 * @return ZAVOD_SUCCESS (0) у разі успішного повернення, запису в лог та звільнення семафора.
 * @return ZAVOD_ERR_INVALID_ARG (-6) якщо worker_id некоректний.
 * @return ZAVOD_ERR_SEM (-2) у разі помилки виклику sem_post().
 * 
 * @see leave_for_break()
 */
int return_from_break(int worker_id);

/**
 * @brief Закриття дескриптора семафора поточного процесу.
 * @details Викликає sem_close(). Якщо функція викликається процесом, який спочатку
 *          створив семафор (батьківський процес / керівник), вона також автоматично
 *          викликає unlink_break_semaphore() для видалення з глобального простору імен.
 * 
 * @return ZAVOD_SUCCESS (0) у разі успішного закриття та (за потреби) видалення.
 * @return ZAVOD_ERR_SEM (-2) у разі помилки виклику sem_close або sem_unlink.
 */
int cleanup_break_semaphore(void);

/**
 * @brief Примусове видалення іменованого семафора із глобальної системи (/dev/shm).
 * @details Викликає sem_unlink(SEM_NAME). Зазвичай викликається керівником при завершенні зміни
 *          або перед запуском тестів для очищення застарілих артефактів.
 * 
 * @return ZAVOD_SUCCESS (0) якщо семафор успішно видалено або він був відсутній (ENOENT).
 * @return ZAVOD_ERR_SEM (-2) у разі системної помилки sem_unlink.
 */
int unlink_break_semaphore(void);

#endif /* SEMAPHORE_UTILS_H */
