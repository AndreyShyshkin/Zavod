#ifndef SEMAPHORE_UTILS_H
#define SEMAPHORE_UTILS_H

/*
 * Модуль керування семафором кімнати відпочинку робітників (Issue #4).
 * 
 * ============================================================================
 * ОБҐРУНТУВАННЯ ВИБОРУ POSIX СЕМАФОРІВ НАД SYSTEM V:
 * 1. Сучасний стандарт: POSIX.1b є стандартом реального часу для Linux,
 *    на відміну від застарілих та складних у супроводі засобів System V IPC.
 * 2. Простір імен: Іменування семафора через зрозумілий рядок ("/zavod_break_sem")
 *    відображається у віртуальній пам'яті ядра /dev/shm, що гарантує відсутність
 *    конфліктів та колізій ключів ftok.
 * 3. Надійність та простота API: Лаконічні функції sem_wait() та sem_post()
 *    не вимагають ініціалізації складних структур struct sembuf та об'єднань union semun.
 * 4. Контроль життєвого циклу: Механізм sem_unlink() забезпечує коректне
 *    видалення семафора з системи, а sem_close() — звільнення дескриптора процесом.
 * ============================================================================
 */

#include <stdbool.h>
#include <semaphore.h>
#include "common.h"

/*
 * Ініціалізація іменованого семафора перерв.
 * Створює або підключається до наявного семафора з початковим значенням 1
 * (дозволяє перебувати на перерві лише одному робітнику одночасно).
 * 
 * Повертає:
 *   ZAVOD_SUCCESS (0) у разі успіху, або ZAVOD_ERR_SEM у разі помилки.
 */
int init_break_semaphore(void);

/*
 * Вихід робітника на перерву.
 * Здійснює блокуюче захоплення семафора (sem_wait) та фіксує час початку.
 * 
 * Параметри:
 *   worker_id - ідентифікатор робітника (наприклад, WORKER_INSPECTOR_ID).
 * 
 * Повертає:
 *   ZAVOD_SUCCESS (0) у разі успішного входу на перерву, або від'ємний код помилки.
 */
int leave_for_break(int worker_id);

/*
 * Повернення робітника з перерви.
 * Фіксує час повернення, виконує атомарний запис у break_log.txt
 * та звільняє семафор (sem_post), відкриваючи доступ іншому робітнику.
 * 
 * Параметри:
 *   worker_id - ідентифікатор робітника.
 * 
 * Повертає:
 *   ZAVOD_SUCCESS (0) у разі успішного повернення та логування, або від'ємний код помилки.
 */
int return_from_break(int worker_id);

/*
 * Очищення локальних ресурсів семафора поточного процесу (sem_close).
 * Якщо викликається процесом-власником (керівником), також автоматично
 * видаляє семафор із системи (sem_unlink).
 * 
 * Повертає:
 *   ZAVOD_SUCCESS (0) у разі успіху, або ZAVOD_ERR_SEM у разі помилки.
 */
int cleanup_break_semaphore(void);

/*
 * Примусове видалення іменованого семафора із системи (sem_unlink).
 * Зазвичай викликається батьківським процесом (керівником) при завершенні зміни.
 * 
 * Повертає:
 *   ZAVOD_SUCCESS (0) у разі успіху, або ZAVOD_ERR_SEM у разі помилки.
 */
int unlink_break_semaphore(void);

#endif /* SEMAPHORE_UTILS_H */
