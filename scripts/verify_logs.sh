#!/usr/bin/env bash
# =============================================================================
# Скрипт валідації журналу перерв (break_log.txt)
# Перевіряє відсутність перетинів часових інтервалів між перебуваннями
# робітників у кімнаті відпочинку (гарантія взаємного виключення семафора).
#
# Усі коментарі та повідомлення виконані українською мовою.
# =============================================================================

set -uo pipefail

LOG_FILE="${1:-break_log.txt}"

echo "================================================================="
echo "ВАЛІДАЦІЯ ЖУРНАЛУ ПЕРЕРВ РОБІТНИКІВ: $LOG_FILE"
echo "================================================================="

if [ ! -f "$LOG_FILE" ]; then
    echo "[ПОМИЛКА] Файл $LOG_FILE не існує!"
    exit 1
fi

TOTAL_LINES=$(wc -l < "$LOG_FILE")
if [ "$TOTAL_LINES" -eq 0 ]; then
    echo "[ПОМИЛКА] Файл $LOG_FILE порожній!"
    exit 1
fi

echo "Знайдено записів для перевірки: $TOTAL_LINES"
echo "Аналіз неперетинності інтервалів..."

PREV_WORKER=""
PREV_END=""
LINE_NUM=0
ERRORS_FOUND=0

while IFS= read -r line || [ -n "$line" ]; do
    LINE_NUM=$((LINE_NUM + 1))

    # Вилучення ідентифікатора робітника
    WORKER=$(echo "$line" | sed -n 's/.*\[Робітник *\([0-9]*\)\].*/\1/p')

    # Вилучення часових міток виходу та повернення
    START_TIME=$(echo "$line" | sed -n 's/.*Вихід: *\([0-9 :-]*\.[0-9]*\).*/\1/p')
    END_TIME=$(echo "$line" | sed -n 's/.*Повернення: *\([0-9 :-]*\.[0-9]*\).*/\1/p')

    if [ -z "$START_TIME" ] || [ -z "$END_TIME" ]; then
        # Якщо лог без мілісекунд, пробуємо стандартний формат
        START_TIME=$(echo "$line" | sed -n 's/.*Вихід: *\([0-9 :-]*\).*/\1/p')
        END_TIME=$(echo "$line" | sed -n 's/.*Повернення: *\([0-9 :-]*\).*/\1/p')
    fi

    # 1. Перевірка: час виходу не може бути пізнішим за час повернення
    if [[ "$START_TIME" > "$END_TIME" ]]; then
        echo "[ПОМИЛКА] Рядок $LINE_NUM: час виходу ($START_TIME) пізніший за час повернення ($END_TIME)!"
        ERRORS_FOUND=$((ERRORS_FOUND + 1))
    fi

    # 2. Перевірка: поточний робітник не міг зайти до того, як вийшов попередній
    if [ -n "$PREV_END" ]; then
        if [[ "$START_TIME" < "$PREV_END" ]]; then
            echo "[КРИТИЧНО] Рядок $LINE_NUM: ВИЯВЛЕНО ПЕРЕТИН ІНТЕРВАЛІВ!"
            echo "           Робітник #$WORKER зайшов о: $START_TIME"
            echo "           Попередній робітник #$PREV_WORKER ще був у кімнаті до: $PREV_END"
            ERRORS_FOUND=$((ERRORS_FOUND + 1))
        fi
    fi

    PREV_WORKER="$WORKER"
    PREV_END="$END_TIME"
done < "$LOG_FILE"

echo "-----------------------------------------------------------------"
if [ "$ERRORS_FOUND" -eq 0 ]; then
    echo "[УСПІХ] Валідацію пройдено на 100%! Жодного перекриття інтервалів не виявлено."
    echo "        Взаємне виключення (Mutual Exclusion) семафора суворо дотримано."
    echo "================================================================="
    exit 0
else
    echo "[НЕВДАЧА] Виявлено помилок у журналі: $ERRORS_FOUND"
    echo "================================================================="
    exit 1
fi
